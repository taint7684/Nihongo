import fs from 'node:fs';
import { lessons } from '../src/content.js';

const gates = JSON.parse(fs.readFileSync('evaluation/done-gates.json', 'utf8'));
const incomplete = gates.levels.N5.items.kanji.filter((row) => !row.complete);
const lessonById = new Map(lessons.map((l) => [l.id, l]));
const groups = new Map();

const distractorPool = [
  'がくせい', 'せんせい', 'がっこう', 'だいがく', 'せんこう', 'みなと', 'でんしゃ', 'えき',
  'みせ', 'ほん', 'やま', 'かわ', 'うみ', 'ひと', 'こども', 'ともだち', 'いち', 'に',
  'さん', 'よん', 'ご', 'ろく', 'なな', 'はち', 'きゅう', 'じゅう', 'ひゃく', 'せん', 'まん',
];

for (const row of incomplete) {
  let lessonId = null;
  let lesson = null;
  let kanji = null;
  let wordKey = null;
  let word = null;
  for (const candidateId of row.lessonIds) {
    const candidateLesson = lessonById.get(candidateId);
    const candidateKanji = candidateLesson?.kanji?.find((k) => k.char === row.text);
    const candidateKey = candidateKanji?.wordKey || String(candidateKanji?.inWord || '').split(/[（(]/u, 1)[0].trim();
    const candidateWord = candidateLesson?.words?.find((w) => w.text === candidateKey);
    if (candidateLesson && candidateKanji && candidateWord?.reading) {
      lessonId = candidateId;
      lesson = candidateLesson;
      kanji = candidateKanji;
      wordKey = candidateKey;
      word = candidateWord;
      break;
    }
  }
  if (!lesson) {
    console.error('Missing kanji word link', row.text, row.lessonIds.join(','));
    continue;
  }
  const chars = [...wordKey].filter((c) => lesson.kanji.some((k) => k.char === c));
  const distractors = distractorPool.filter((r) => r !== word.reading).slice(0, 2);
  const question = {
    id: `n5sK-${lessonId}-${row.text.codePointAt(0).toString(16)}`,
    assessment: true,
    sourceLessonId: lessonId,
    validationStatus: 'Project-authored kanji reading item using an existing lesson word; not independently reviewed',
    prompt: `Đọc từ mới trong câu: 「${wordKey}」を読みます。\nCách đọc của ${wordKey} là gì?`,
    choices: [word.reading, ...distractors],
    answer: 0,
    explanation: `Cách đọc của ${wordKey} là ${word.reading}. Đây là cách đọc trong từ đã học, không phải mọi âm của chữ ${row.text}.`,
    skill: 'đọc Kanji trong từ',
    assessesKanji: chars,
    wordKey,
    usageId: `${lessonId}:${wordKey}`,
    wordLinks: [{ wordKey, usageId: `${lessonId}:${wordKey}`, kind: 'kanji-reading' }],
    assessmentScope: 'Reading in the explicitly linked word only; not recognition/writing or all readings.',
  };
  if (!groups.has(lessonId)) groups.set(lessonId, []);
  groups.get(lessonId).push(question);
}

const lessonsOut = [...groups.entries()].map(([lessonId, questions]) => {
  const lesson = lessonById.get(lessonId);
  return {
    id: `n5-kanji-assessment-supp-${lessonId}`,
    number: `ĐÁNH GIÁ KANJI ${lessonId}`,
    stage: 'Đánh giá Kanji',
    level: 'N5',
    track: 'assessment',
    chapter: 'Đọc Kanji trong từ',
    kind: 'assessment',
    assessmentFor: lessonId,
    checkpoint: false,
    prerequisite: null,
    minutes: 8,
    glyph: '読',
    title: `Đọc Kanji trong từ: ${lessonId}`,
    subtitle: 'Đọc từ mới chứa chữ đã học',
    goal: 'Đọc đúng cách đọc của chữ Kanji trong từ đã học.',
    intro: 'Mỗi câu dùng một từ thật trong bài. Đây là đánh giá đọc trong từ, không phải viết hay mọi âm đọc.',
    cards: [],
    words: [],
    notes: ['Đọc trong từ là bằng chứng hẹp; không suy ra viết được hoặc nhớ mọi nghĩa.'],
    activity: 'Đọc từ trong câu, chọn cách đọc, xem giải thích.',
    sources: [{ name: 'Học liệu đánh giá dự án tự soạn; không phải đề JLPT chính thức', url: 'https://www.jlpt.jp/e/samples/forlearners.html' }],
    questions,
    listeningTasks: [],
  };
});

const body = `// Generated by scripts/build-n5-kanji-assessment.mjs. Do not edit by hand.\nexport const n5KanjiAssessmentSupplement = ${JSON.stringify(lessonsOut, null, 2)};\n`;
fs.writeFileSync('src/n5-kanji-assessment-supp.js', body);
console.log(JSON.stringify({ incomplete: incomplete.length, lessons: lessonsOut.length, questions: lessonsOut.reduce((n, l) => n + l.questions.length, 0) }));